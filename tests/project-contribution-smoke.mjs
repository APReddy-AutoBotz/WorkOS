import assert from 'node:assert/strict';
import {calculateProjectContribution as calculate} from '../shared/project-contribution.mjs';
import {actualFixtureCapacity} from './support/actual-work-test.mjs';

const day = '2026-10-24';
const row = (hoursExact, patch = {}) => ({id: 'entry', date: day, status: 'Approved', hoursExact, disposition: 'included', reason: null, ...patch});
const worker = (employeeId, hours, patch = {}) => {
  const capacity = actualFixtureCapacity(day);
  capacity.employeeId = employeeId;
  return {employeeId, capacity, rows: [row(hours)], ...patch};
};
const input = workers => ({projectId: 'synthetic-project', startsOn: day, endsOn: day, workers});
let result = calculate(input([worker('one', '4'), worker('two', '2')]));
assert.equal(result.eligibleAvailableHoursExact, '16');
assert.equal(result.includedHoursExact, '6');
assert.equal(result.percentage.displayPercent, '37.5');
assert.equal(result.workerCount, 2);
assert.equal(result.rows[0].percentage.displayPercent, '50');
assert.throws(() => calculate(input([worker('one', '4'), worker('one', '4')])), /distinct workers/);
assert.throws(() => calculate(input([worker('one', '4', {rows: [row('4', {date: '2026-10-23'})]})])), /selected period/);
assert.throws(() => calculate({...input([worker('one', '4')]), endsOn: '2026-10-25'}), /periods must match/);

result = calculate(input([worker('one', '0.00000000000000001'), worker('two', '20')]));
assert.equal(result.includedHoursExact, '20.00000000000000001');
assert.equal(result.percentage.numeratorExact, '2000000000000000001');
assert.equal(result.percentage.denominatorExact, '16000000000000000');
assert.equal(result.percentage.displayPercent, '125');

const mixed = worker('one', '0', {rows: [row('3'), row('2', {disposition: 'excluded'}), row('7', {status: 'Submitted', disposition: 'not_approved'}), row('1', {status: 'Draft', disposition: 'not_approved'}), row('4', {status: 'Rejected', disposition: 'not_approved'})]});
result = calculate(input([mixed]));
assert.equal(result.includedHoursExact, '3');
assert.deepEqual(result.controls.hoursByStatus, {Draft: '1', Submitted: '7', Rejected: '4', Approved: '5'});
assert.equal(result.controls.knownExcludedHoursExact, '2');
const unresolved = worker('two', '2', {rows: [row('2', {disposition: 'unresolved', reason: 'APPROVAL_EVIDENCE_UNAVAILABLE'})]});
result = calculate(input([mixed, unresolved]));
assert.equal(result.status, 'unavailable');
assert.equal(result.includedHoursExact, null);
assert.equal(result.percentage, null);
assert.equal(result.controls.knownIncludedHoursExact, '3');
assert.equal(result.controls.unresolvedApprovedHoursExact, '2');

const unavailable = worker('missing', '4');
unavailable.capacity = {...actualFixtureCapacity(day, {profiles: []}), employeeId: 'missing'};
result = calculate(input([mixed, unavailable]));
assert.equal(result.status, 'unavailable');
assert.equal(result.eligibleAvailableHoursExact, null);
assert.equal(result.percentage, null);
assert.equal(result.includedHoursExact, '7');
const zero = worker('zero', '0');
zero.capacity = {...actualFixtureCapacity(day, {worker: {id: 'zero', legalEntityId: 'synthetic-legal', status: 'Exited', joiningDate: null, exitDate: '2026-10-23'}}), employeeId: 'zero'};
result = calculate(input([zero]));
assert.equal(result.status, 'not_applicable');
assert.equal(result.eligibleAvailableHoursExact, '0');
assert.equal(result.percentage, null);
result = calculate(input([]));
const notJoined = worker('not-joined', '0');
notJoined.capacity = {...actualFixtureCapacity(day, {worker: {id: 'not-joined', legalEntityId: 'synthetic-legal', status: 'Active', joiningDate: '2026-10-25', exitDate: null}}), employeeId: 'not-joined'};
const beforeJoining = calculate(input([notJoined]));
assert.equal(beforeJoining.status, 'not_applicable');
assert.equal(beforeJoining.eligibleAvailableHoursExact, '0');
assert.equal(beforeJoining.percentage, null);
assert.equal(result.status, 'not_applicable');
assert.deepEqual(result.reasonCodes, ['NO_VISIBLE_COHORT']);
result = calculate({...input([mixed]), periodIsActual: false});
assert.equal(result.status, 'unavailable');
assert.equal(result.percentage, null);
result = calculate({...input([mixed]), sourceLimited: true});
assert.equal(result.status, 'unavailable');
for (const key of ['workerCount', 'rows', 'controls', 'includedHoursExact', 'eligibleAvailableHoursExact', 'percentage']) assert.equal(result[key], null, key);
console.log('Project contribution exact aggregate, distinct cohort, consistent period, state controls, unresolved approval, missing/zero capacity, future period and truncation vectors passed.');
